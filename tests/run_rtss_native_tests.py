"""Run real profile exports only against a proven, separate installation copy.

Requires the transaction EXE generated by Run-RtssTests.ps1 -Compile. Never
launches RTSS.exe, enumerates profiles through the SDK, or saves user profiles.
UpdateProfiles is a real reload request; it is not proof of target game FPS.
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import uuid
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("output", type=Path)
parser.add_argument("--installed", type=Path, required=True)
args = parser.parse_args()
installed = args.installed.resolve()
output = args.output.resolve()
isolated = output / ("native-" + uuid.uuid4().hex)
assert installed != isolated and installed not in isolated.parents
exe = output / "RtssProfileTransactionTests.exe"
assert exe.is_file()


def hashes():
    return {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
            for p in (installed / "Profiles").iterdir() if p.is_file()}


def rate_profile(text, limit, denominator=1, time=0, time_denominator=1):
    for key, value in (("Limit", limit), ("LimitDenominator", denominator),
                       ("LimitTime", time), ("LimitTimeDenominator", time_denominator)):
        text, count = re.subn(rf"(?mi)^{key}=.*$", f"{key}={value}", text)
        assert count == 1, f"Unique {key} required for the native fixture"
    return text


before = hashes()
(isolated / "Profiles").mkdir(parents=True)
for name in ("RTSSHooks64.dll", "RTSS.exe"):
    shutil.copy2(installed / name, isolated / name)
shutil.copy2(installed / "Profiles/Config", isolated / "Profiles/Config")
text = (installed / "Profiles/Global").read_text(encoding="utf-8-sig")
for name, limit, denominator, time in (("Global", 97, 1, 0), ("existing.exe.cfg", 30, 1, 0),
                                      ("fractional.exe.cfg", 59940, 1000, 0), ("time.exe.cfg", 0, 1, 16667)):
    (isolated / "Profiles" / name).write_text(rate_profile(text, limit, denominator, time), encoding="utf-8")
(isolated / "Profiles/time-fractional.exe.cfg").write_text(rate_profile(text, 0, 1, 1666667, 100), encoding="utf-8")
sparse = re.sub(r"(?mi)^(LimitDenominator|LimitTime|LimitTimeDenominator)=.*\n", "", rate_profile(text, 30))
(isolated / "Profiles/sparse.exe.cfg").write_text(sparse, encoding="utf-8")
def rtss_processes():
    observed = subprocess.run(["pwsh", "-NoProfile", "-Command",
        "@(@(Get-Process -Name RTSS -ErrorAction SilentlyContinue) | Select-Object Id, Path) | ConvertTo-Json -Compress"],
        text=True, capture_output=True, timeout=20)
    if observed.returncode:
        return {"error": observed.stderr}
    return json.loads(observed.stdout) if observed.stdout.strip() else []

processes_before = rtss_processes()
result = {"directory_source": "explicit installed argument; distinct copied installation",
          "installed": str(installed), "copied_rtss_exe_sha256": hashlib.sha256((isolated / "RTSS.exe").read_bytes()).hexdigest(),
          "rtss_processes_before": processes_before, "fully_offline": processes_before == [],
          "native_apply_running_flag": True, "native_init_running_flag": False,
          "copied_rtss_launched": False, "dll_path": str(isolated / "RTSSHooks64.dll"), "isolated": str(isolated), "dll_sha256": hashlib.sha256((isolated / "RTSSHooks64.dll").read_bytes()).hexdigest()}
try:
    process = subprocess.run([str(exe), str(output), str(isolated)], text=True, capture_output=True, timeout=60)
    result.update(returncode=process.returncode, stdout=process.stdout, stderr=process.stderr)
    print(process.stdout, end="")
    print(process.stderr, end="")
    init_exe = output / "RtssInitializationTests.exe"
    if process.returncode == 0 and init_exe.is_file():
        initialization = subprocess.run([str(init_exe), str(output), str(isolated)], text=True, capture_output=True, timeout=60)
        result.update(initialization_returncode=initialization.returncode, initialization_stdout=initialization.stdout, initialization_stderr=initialization.stderr)
        print(initialization.stdout, end="")
        print(initialization.stderr, end="")
finally:
    after = hashes()
    result["rtss_processes_after"] = rtss_processes()
    result["original_profiles_unchanged"] = before == after
    result["original_profile_count"] = len(before)
    result["changed_original_profiles"] = sorted(k for k in before.keys() | after.keys() if before.get(k) != after.get(k))
    (output / "native-result.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
assert result["original_profiles_unchanged"], "Original profile files changed during isolated test"
assert result.get("returncode") == 0, "Native transaction test failed"
assert result.get("initialization_returncode", 0) == 0, "Native initialization test failed"
print(f"Original RTSS profiles unchanged: {len(before)} file hashes verified.")
